/**
 * mergeMessages deep-merges base + platform messages for each locale.
 * @param {Object} platformMessages - e.g. EXT_MESSAGES or DESKTOP_MESSAGES
 * @returns {Object} merged messages keyed by locale
 */
export function mergeMessages(platformMessages) {
  const result = {};
  for (const locale of Object.keys(BASE_MESSAGES)) {
    result[locale] = {
      ...BASE_MESSAGES[locale],
      ...(platformMessages[locale] || {}),
    };
  }
  return result;
}
